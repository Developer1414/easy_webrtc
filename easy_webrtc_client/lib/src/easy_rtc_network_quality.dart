/// Грубая оценка качества WebRTC-соединения с партнёром на основе
/// состояния ICE/PeerConnection.
///
/// Отдельный сигналинг для этого не нужен: WebRTC-канал — это прямая
/// связь между двумя участниками, и если у партнёра портится сеть, ваш
/// собственный [RTCPeerConnectionState] тоже перейдёт в disconnected/
/// failed — это одно и то же соединение, видимое с обеих сторон.
enum NetworkQuality {
  /// Соединение установлено и стабильно (или ещё не начиналось —
  /// specifically не путаем "рано" с "плохо")
  good,

  /// ICE временно потерял связность и пытается восстановиться сам —
  /// кратковременные проблемы сети, смена Wi-Fi/LTE и т.п.
  unstable,

  /// Соединение разорвано и не восстановилось
  lost,
}
