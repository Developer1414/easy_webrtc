/// Абстракция хранилища участников комнат. По умолчанию используется
/// InMemoryRoomStore — достаточно, пока сервер работает как один процесс.
///
/// Если понадобится несколько инстансов сервера за балансировщиком —
/// можно реализовать этот интерфейс поверх общего хранилища (Redis и
/// т.п.) для СПИСКА участников. Учти: сама ретрансляция WebSocket-
/// сообщений в этом пакете происходит в памяти конкретного процесса —
/// для полноценного мульти-инстанс релея нужен либо sticky sessions на
/// балансировщике (оба участника попадают на один и тот же инстанс),
/// либо свой relay-слой поверх pub/sub — это пакетом не реализовано.
abstract class RoomStore {
  Future<List<String>> join(String roomId, String userId);
  Future<List<String>?> leave(String userId);
  Future<String?> roomOf(String userId);
  Future<List<String>> membersOf(String roomId);
}